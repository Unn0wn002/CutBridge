$.evalFile(new File("C:/NativeAEInput/common.jsx"));
CB.execute("campaign", function () {
    CB.fresh();
    CutBridgeContract.loadManifest(CB.packages[1].path);
    CB.build("V001 initial native Build"); CB.handoff();
    var c = CB.comp(), beforeIds = CB.ids(), beforeLayers = c.numLayers;
    CB.build("V001 repeated Build");
    CB.check("V001 repeated Build has no duplicates", CB.equal(beforeIds, CB.ids()) && beforeLayers === c.numLayers);
    var beauty = c.layer("BEAUTY");
    if (!beauty) throw CB.insufficient("Representative BEAUTY layer is unavailable");
    var artist = c.layers.addSolid([0.2, 0.3, 0.4], "Artist Annotation", 320, 180, 1, c.duration);
    artist.name = "Artist Annotation"; artist.comment = "ARTIST_UNMANAGED";
    artist.property("ADBE Transform Group").property("ADBE Position").setValue([37, 49]);
    beauty.parent = artist; beauty.shy = true; beauty.startTime = 1 / c.frameRate;
    beauty.inPoint = beauty.startTime; beauty.outPoint = c.duration;
    var t = beauty.property("ADBE Transform Group"), opacity = t.property("ADBE Opacity");
    t.property("ADBE Position").setValue([71, 83]);
    t.property("ADBE Scale").setValue([97, 103]);
    t.property("ADBE Rotate Z").setValue(12);
    opacity.setValueAtTime(0, 73); opacity.setValueAtTime(1 / c.frameRate, 61); opacity.expression = "value";
    var slider = beauty.property("ADBE Effect Parade").addProperty("ADBE Slider Control");
    slider.property("ADBE Slider Control-0001").setValue(42);
    var mask = beauty.property("ADBE Mask Parade").addProperty("ADBE Mask Atom"), shape = new Shape();
    shape.vertices = [[10, 10], [100, 10], [100, 100], [10, 100]];
    shape.inTangents = [[0, 0], [0, 0], [0, 0], [0, 0]];
    shape.outTangents = [[0, 0], [0, 0], [0, 0], [0, 0]]; shape.closed = true;
    mask.property("ADBE Mask Shape").setValue(shape);
    mask.property("ADBE Mask Opacity").setValue(87);
    artist.moveToEnd();
    var unrelatedFolder = app.project.items.addFolder("Unrelated Folder"); unrelatedFolder.comment = "Preserve unrelated folder";
    var unrelatedComp = app.project.items.addComp("Unrelated Comp", 64, 64, 1, 1, 24);
    unrelatedComp.parentFolder = unrelatedFolder; unrelatedComp.comment = "Preserve unrelated comp";
    var unrelatedSolid = unrelatedComp.layers.addSolid([0.7, 0.1, 0.2], "Unrelated Footage", 64, 64, 1, 1);
    unrelatedSolid.source.name = "Unrelated Footage"; unrelatedSolid.source.comment = "Preserve unrelated source";
    unrelatedSolid.source.parentFolder = unrelatedFolder;
    c.parentFolder.parentFolder.comment = "Artist/studio package note: preserve verbatim";
    var preserved = CB.preservation(); CB.report.artist_before = preserved;
    app.project.save(new File(CB.projectPath(1)));
    CB.check("V001 artist project saved", new File(CB.projectPath(1)).exists);
    for (var version = 2; version <= 3; version++) {
        CB.revision(CB.packages[version].path, version, true);
        CB.check("V00" + version + " preserves concrete artist property values", CB.equal(preserved, CB.preservation()), {expected: preserved, actual: CB.preservation()});
        CB.handoff(); CB.build("V00" + version + " native Build/QC");
        CB.check("V00" + version + " repeated Build preserves artist values", CB.equal(preserved, CB.preservation()));
        beforeIds = CB.ids(); beforeLayers = c.numLayers;
        CB.build("V00" + version + " repeated Build");
        CB.check("V00" + version + " repeated Build has no duplicates", CB.equal(beforeIds, CB.ids()) && beforeLayers === c.numLayers);
        var state = CutBridgeContract.getState(), expectedTag = CutBridgeContract.managedTag("layer", state.manifest, "BEAUTY");
        CB.check("V00" + version + " exact managed ownership tag", beauty.comment === expectedTag);
        CB.check("V00" + version + " source belongs to selected Blender package", String(beauty.source.file.fsName).replace(/\\/g, "/").indexOf(String(new File(CB.packages[version].path).parent.fsName).replace(/\\/g, "/") + "/") === 0);
        app.project.save(new File(CB.projectPath(version)));
        CB.check("V00" + version + " project saved", new File(CB.projectPath(version)).exists);
    }
    CB.report.artist_after = CB.preservation();
    CB.save(CB.config.output_root + "/preservation-baseline.json", preserved);
});
